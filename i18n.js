/* ---------------------------------------------------------------------
 * แปลข้อความ  T('key', {n: 5}, 'th')
 * ถ้าไม่มีคีย์ในภาษานั้น จะถอยไปใช้ไทย แล้วค่อยคืนคีย์ดิบ
 * ------------------------------------------------------------------- */
function T(key, vars, lang) {
  const L = DICT[lang] || DICT.th;
  let s = L[key];
  if (s === undefined) s = DICT.th[key];
  if (s === undefined) return key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

/* แปลง GoR เป็นป้ายคิว/ดั้งตามภาษา */
function rankLabel(gor, lang) {
  if (gor == null) return '—';
  if (gor >= 2100) return T('rank.dan', { n: Math.min(9, Math.floor((gor - 2000) / 100)) }, lang);
  return T('rank.kyu', { n: Math.min(30, Math.max(1, Math.ceil((2100 - gor) / 100))) }, lang);
}

